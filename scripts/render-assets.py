"""List local media so absent reference assets keep placeholders without 404s."""
from pathlib import Path
import json
root = Path(__file__).resolve().parents[1]
assets = sorted('/' + p.relative_to(root / 'public').as_posix() for p in (root / 'public/assets').rglob('*') if p.is_file())
(root / 'public/scripts/asset-manifest.js').write_text('/* Generated by scripts/render-assets.py; do not edit. */\nwindow.hypertuneAssets = new Set(' + json.dumps(assets) + ');\n')
print(f'Asset inventory: {len(assets)} local files')

# Keep available resources usable without JavaScript as well.
import re
home = root / 'public/index.html'
page = home.read_text()
def source(match):
    tag = re.sub(r'\s+src="[^"]*"', '', match[0])
    path = re.search(r'data-local-src="([^"]+)"', tag)[1]
    return tag.replace('data-local-src=', 'src="' + path + '" data-local-src=', 1) if path in assets else tag
page = re.sub(r'<(?:img|source)\b[^>]*data-local-src="[^"]*"[^>]*>', source, page)
home.write_text(page)
